/**
 * Turn a copy of the web app's database into SQL the phone app can replay.
 *
 *   node scripts/make-seed.mjs [source.db] [output.ts]
 *
 * Why SQL and not the .db file: the sqlite-wasm build cannot deserialize a
 * WAL-mode image into an in-memory connection (`SQLITE_NOTADB`), its Node VFS
 * is virtual so it cannot open a path, and its documented import path
 * (`oo1.OpfsDb.importDb`) is browser-only and cannot be tested from here. SQL
 * text has none of those problems and runs identically in both engines.
 *
 * The vectors go in as `x'…'` blob literals, so the 384 float32 values survive
 * byte for byte and retrieval keeps working.
 *
 * The output holds the journal's own text. It is not committed.
 */
import Database from 'better-sqlite3';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const source = resolve(process.argv[2] ?? 'data/fermentario.db');
const out = resolve(process.argv[3] ?? 'src/lib/platform/seed.generated.ts');

const db = new Database(source, { readonly: true, fileMustExist: true });
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const blob = (v) => {
	const b = Buffer.isBuffer(v) ? v : new Uint8Array(v.buffer ?? v, v.byteOffset ?? 0, v.byteLength ?? v.length);
	return `x'${b.toString('hex')}'`;
};

const parts = [];
let notes = 0;
let tags = 0;
let vectors = 0;
let recaps = 0;
let asks = 0;

for (const n of db.prepare('SELECT id, content, created_at, updated_at FROM notes').all()) {
	parts.push(
		`INSERT INTO notes (id, content, created_at, updated_at) VALUES (${q(n.id)}, ${q(n.content)}, ${n.created_at}, ${n.updated_at});`,
		`INSERT INTO notes_fts (content, note_id) VALUES (${q(n.content)}, ${q(n.id)});`
	);
	notes++;
}
for (const t of db.prepare('SELECT note_id, tag FROM note_tags').all()) {
	parts.push(`INSERT INTO note_tags (note_id, tag) VALUES (${q(t.note_id)}, ${q(t.tag)});`);
	tags++;
}
for (const v of db.prepare('SELECT note_id, vector FROM note_vectors').all()) {
	parts.push(`INSERT INTO note_vectors (note_id, vector) VALUES (${q(v.note_id)}, ${blob(v.vector)});`);
	vectors++;
}
for (const r of db.prepare('SELECT week_key, content, created_at, updated_at FROM weekly_recaps').all()) {
	parts.push(
		`INSERT INTO weekly_recaps (week_key, content, created_at, updated_at) VALUES (${q(r.week_key)}, ${q(r.content)}, ${r.created_at}, ${r.updated_at});`
	);
	recaps++;
}
for (const a of db
	.prepare('SELECT id, question, answer, sources, created_at FROM ask_history')
	.all()) {
	parts.push(
		`INSERT INTO ask_history (id, question, answer, sources, created_at) VALUES (${q(a.id)}, ${q(a.question)}, ${q(a.answer)}, ${q(a.sources)}, ${a.created_at});`
	);
	asks++;
}
db.close();

const header = `/**
 * GENERATED by scripts/make-seed.mjs from a copy of the web app's database.
 * Do not edit, and do not commit: it contains the journal's own text.
 *
 * ${notes} notes, ${tags} tags, ${vectors} vectors, ${recaps} recaps, ${asks} asks.
 */
export const SEED_SQL = ${JSON.stringify(parts.join('\n'))};
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, header);
console.log(
	`seed written: ${out}\n  ${notes} notes, ${tags} tags, ${vectors} vectors, ${recaps} recaps, ${asks} asks`
);
